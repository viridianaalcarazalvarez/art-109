const FADE_MS = 180;

const phraseEl = document.getElementById("phrase");
const asciiStage = document.getElementById("ascii-stage");
const asciiPanels = asciiArtworks.map((art) => {
  const pre = document.createElement("pre");
  pre.className = "ascii-art";
  pre.setAttribute("aria-hidden", "true");
  pre.textContent = art;
  asciiStage.appendChild(pre);
  return pre;
});

let currentIndex = -1;
let lastArtIndex = -1;
let fadeTimeout = null;
let shuffledOrder = [];
let orderPos = 0;

function shuffleArray(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = arr[i];
    arr[i] = arr[j];
    arr[j] = tmp;
  }
}

function initShuffledOrder() {
  shuffledOrder = phrases.map((_, i) => i);
  shuffleArray(shuffledOrder);
  orderPos = 0;
}

function randomPhrase() {
  if (!shuffledOrder.length) initShuffledOrder();

  if (orderPos >= shuffledOrder.length) initShuffledOrder();

  let next = shuffledOrder[orderPos++];

  if (next === currentIndex && phrases.length > 1) {
    if (orderPos >= shuffledOrder.length) initShuffledOrder();
    next = shuffledOrder[orderPos++];
    if (next === currentIndex) {
      for (let i = 0; i < phrases.length; i++) {
        if (i !== currentIndex) {
          next = i;
          break;
        }
      }
    }
  }

  return next;
}

function hideAllAscii() {
  asciiPanels.forEach((panel) => panel.classList.remove("visible"));
}

function randomAsciiIndex() {
  let next;
  do {
    next = Math.floor(Math.random() * asciiPanels.length);
  } while (next === lastArtIndex && asciiPanels.length > 1);
  return next;
}

function showAsciiPanel(index) {
  hideAllAscii();
  asciiPanels[index].classList.add("visible");
}

function showPhrase(index, instant = false) {
  clearTimeout(fadeTimeout);

  const apply = () => {
    const entry = phrases[index];
    currentIndex = index;
    phraseEl.textContent = entry.text;
    phraseEl.classList.remove("fade-out");

    hideAllAscii();
    if (entry.ascii) {
      lastArtIndex = randomAsciiIndex();
      showAsciiPanel(lastArtIndex);
    }
  };

  hideAllAscii();

  if (instant || !phraseEl.textContent) {
    apply();
    return;
  }

  if (phraseEl.classList.contains("fade-out")) {
    apply();
    return;
  }

  phraseEl.classList.add("fade-out");
  fadeTimeout = setTimeout(apply, FADE_MS);
}

function nextPhrase() {
  showPhrase(randomPhrase());
}

document.addEventListener("click", nextPhrase);
document.addEventListener("keydown", (e) => {
  if (e.key === " " || e.key === "Enter") {
    e.preventDefault();
    nextPhrase();
  }
});

showPhrase(randomPhrase(), true);
